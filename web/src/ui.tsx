export const Pill = ({ level, children }: { level: string; children: ReactNode }) => <span className={`pill ${level}`}>{children}</span>

export function Detail({ label, value }: { label: string; value: ReactNode }) {
  return <div className="detail"><span>{label}</span><span>{value}</span></div>
}

export function Sheet({ title, onClose, children }: { title: string; onClose: () => void; children: ReactNode }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [onClose])
  return (
    <div className="scrim" onClick={onClose}>
      <div className="sheet" role="dialog" aria-label={title} onClick={(e) => e.stopPropagation()}>
        <h3>{title}</h3>
        {children}
      </div>
    </div>
  )
}

export function Field({ label, value, onChange, type = 'text', placeholder, inputMode }: {
  label: string; value: string; onChange: (v: string) => void; type?: string; placeholder?: string
  inputMode?: 'numeric' | 'decimal' | 'text'
}) {
  return (
    <label className="f">
      {label}
      <input type={type} value={value} placeholder={placeholder} inputMode={inputMode} onChange={(e) => onChange(e.target.value)} />
    </label>
  )
}
